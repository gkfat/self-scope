const rows = (table: string): string[][] => table.trim().split('\n').map((line) => line.split('|'));

const orientationReading = (fields: string[]): RuneOrientationReading => {
    const [
        love = '',
        work = '',
        self = '',
        relationship = '',
        ...reflections
    ] = fields;

    return {
        love, work, self, relationship, reflections,
    };
};

const REVERSED = new Map(rows(REVERSED_TABLE).map(([name = '', ...fields]) => [name, orientationReading(fields)]));

/** Indexed by rune number, 0 (Fehu) to 23 (Othala). */
export const RUNE_MEANINGS: readonly RuneMeaning[] = rows(UPRIGHT_TABLE).map(([
    name = '',
    traditional = '',
    modern = '',
    light = '',
    shadow = '',
    growthTask = '',
    ...upright
]) => {
    const reversed = REVERSED.get(name);

    return {
        name, traditional, modern, light, shadow, growthTask, upright: orientationReading(upright), ...(reversed ? { reversed } : {}),
    };
});

/** The reading of the side that was drawn: a rune that cannot be reversed only has its upright side. */
export const runeSide = (index: number, orientation: RuneOrientation): RuneOrientationReading | undefined => {
    const meaning = RUNE_MEANINGS[index];

    return orientation === 'reversed' ? meaning?.reversed : meaning?.upright;
};
